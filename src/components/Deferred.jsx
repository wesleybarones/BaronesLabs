import { Suspense, useEffect, useLayoutEffect, useRef, useState } from 'react'
import { isBot } from '../lib/bot'

/*
  Sections below the first screen: content always in the page, interactive version on demand.

  - SEO: the build puts a static copy of every section in index.html (#bl-static, src/sections-static.html,
    regenerated by scripts/capture-hero-shell.cjs). Search engines and AI crawlers that don't run JavaScript
    read the whole page from the HTML.
  - When React starts, each <Deferred name="..."> takes its static copy into place (the text never leaves
    the DOM), and swaps it for the live, animated component when the visitor gets near it.
  - Performance (TBT/INP): no live section is built during the initial load:
    observing starts on the first real interaction (scroll, wheel, touch, key) and a section turns live within
    ~1 screen of the viewport; menu/anchor navigation turns everything live first (see scrollToId);
    robots get the live sections immediately.
*/
let started = false
let all = false
const START_EVENTS = ['scroll', 'wheel', 'touchstart', 'keydown', 'pointerdown']

function onStart(cb) {
  if (started) return cb(), () => {}
  const go = () => {
    started = true
    START_EVENTS.forEach((e) => window.removeEventListener(e, go))
    window.dispatchEvent(new Event('bl:start'))
  }
  START_EVENTS.forEach((e) => window.addEventListener(e, go, { passive: true, once: true }))
  window.addEventListener('bl:start', cb, { once: true })
  return () => window.removeEventListener('bl:start', cb)
}

export function mountAllSections() {
  all = true
  window.dispatchEvent(new Event('bl:mount-all'))
}

// the build's static copy of a section (null when there is none, e.g. in the single-file preview)
const staticCopy = (name) => (typeof document === 'undefined' ? null : document.querySelector(`#bl-static > [data-sec="${name}"]`))
function dropEmptyHolder() {
  const holder = document.getElementById('bl-static')
  if (holder && !holder.children.length) holder.remove()
}

function Mounted() {
  // tells listeners (header active link, floating button…) that new sections exist in the DOM
  useEffect(() => {
    window.dispatchEvent(new Event('bl:section-mounted'))
  }, [])
  return null
}

export default function Deferred({ name, children, placeholder = '100vh' }) {
  const [on, setOn] = useState(() => all || isBot() || (typeof location !== 'undefined' && location.hash.length > 1))
  const ref = useRef(null)
  const [adopted, setAdopted] = useState(false)

  // static copy → into place (before paint, so nothing moves); live version → the static copy goes away
  useLayoutEffect(() => {
    const node = name && staticCopy(name)
    if (on) {
      node?.remove()
      dropEmptyHolder()
      return
    }
    if (node && ref.current && !ref.current.contains(node)) {
      ref.current.appendChild(node)
      setAdopted(true)
      dropEmptyHolder()
    }
  }, [on, name])

  useEffect(() => {
    if (on) return
    const show = () => setOn(true)
    window.addEventListener('bl:mount-all', show)
    let io
    const stop = onStart(() => {
      io = new IntersectionObserver(([e]) => e.isIntersecting && show(), { rootMargin: '100% 0px' })
      if (ref.current) io.observe(ref.current)
    })
    return () => {
      window.removeEventListener('bl:mount-all', show)
      stop()
      io?.disconnect()
    }
  }, [on])

  // placeholder: holds the static copy (real content) or, without one, reserves space
  const ph = <div ref={ref} data-sec-slot={name} style={adopted ? undefined : { minHeight: placeholder }} />
  if (!on) return ph
  return (
    <Suspense fallback={<div aria-hidden="true" style={{ minHeight: placeholder }} />}>
      <div data-sec={name}>{children}</div>
      <Mounted />
    </Suspense>
  )
}
